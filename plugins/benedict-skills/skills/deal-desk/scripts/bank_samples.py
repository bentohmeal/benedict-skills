def _walk(n, start, drift, seed):
    out, v = [], start
    for k in range(n):
        v *= 1 + drift + 0.035 * math.sin(k * 0.9 + seed) + 0.02 * math.sin(k * 2.3 + seed * 2)
        out.append(round(v, 2))
    return out


